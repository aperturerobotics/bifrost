#!/usr/bin/env bash
# sync.bash - Copy Go's internal/trace packages for trace file parsing.
#
# Usage: ./sync.bash [GOROOT]
#   GOROOT defaults to $(go env GOROOT).
#
# Copies internal/trace, internal/trace/tracev2, internal/trace/version,
# and internal/trace/raw from the Go source tree into this directory,
# rewriting import paths to the spacewave module.

set -euo pipefail

GOROOT_DIR="${1:-$(go env GOROOT)}"
SRC="${GOROOT_DIR}/src/internal/trace"
DST="$(cd "$(dirname "$0")" && pwd)"
MODULE="github.com/s4wave/spacewave/bldr/devtool/trace/parser"

if [[ ! -d "$SRC" ]]; then
  echo "error: $SRC does not exist" >&2
  exit 1
fi

echo "Syncing from: $SRC"
echo "Syncing to:   $DST"
echo "Module path:  $MODULE"

# Record upstream commit.
GO_COMMIT="$(cd "$GOROOT_DIR" && git rev-parse HEAD 2>/dev/null || echo 'unknown')"
GO_DATE="$(cd "$GOROOT_DIR" && git log -1 --format='%ci' HEAD 2>/dev/null || echo 'unknown')"
cat > "$DST/UPSTREAM" <<EOF
Source: \$(go env GOROOT)/src/internal/trace
Go commit: ${GO_COMMIT}
Go commit date: ${GO_DATE}
Sync date: $(date -u '+%Y-%m-%d')
Module rewrite: internal/trace -> ${MODULE}
EOF

# Copy Go BSD-3-Clause license.
if [[ -f "$GOROOT_DIR/LICENSE" ]]; then
  cp "$GOROOT_DIR/LICENSE" "$DST/LICENSE"
else
  echo "warning: no LICENSE found at $GOROOT_DIR/LICENSE" >&2
fi

# Helper: copy non-test .go files from $1 to $2.
copy_go() {
  local src_dir="$1" dst_dir="$2"
  mkdir -p "$dst_dir"
  for f in "$src_dir"/*.go; do
    [[ "$(basename "$f")" == *_test.go ]] && continue
    [[ "$(basename "$f")" == export_*.go ]] && continue
    cp "$f" "$dst_dir/"
  done
}

# Copy main package (skip tracev1.go, internal/).
copy_go "$SRC" "$DST"
rm -f "$DST/tracev1.go"

# Copy sub-packages.
copy_go "$SRC/tracev2" "$DST/tracev2"
copy_go "$SRC/version" "$DST/version"
copy_go "$SRC/raw" "$DST/raw"

# Rewrite import paths.
while IFS= read -r -d '' f; do
  sed -i.bak \
    -e "s|\"internal/trace/tracev2\"|\"${MODULE}/tracev2\"|g" \
    -e "s|\"internal/trace/version\"|\"${MODULE}/version\"|g" \
    -e "s|\"internal/trace/raw\"|\"${MODULE}/raw\"|g" \
    -e "s|\"internal/trace\"|\"${MODULE}\"|g" \
    "$f"
  rm -f "${f}.bak"
  # Mark the copy as generated so local Go style checks skip it.
  { printf '%s\n\n' "// Code generated by sync.bash from Go's internal/trace. DO NOT EDIT."; cat "$f"; } >"${f}.tmp"
  mv "${f}.tmp" "$f"
done < <(find "$DST" -name '*.go' -print0)

echo "Done. Run 'go build ./bldr/devtool/trace/parser/...' from the repo root to verify."
